.git_remote <- function(d) {
  cf <- file.path(d, ".git", "config")
  if (!file.exists(cf)) return(NA_character_)
  a <- readLines(cf, warn = FALSE)
  u <- a[grepl("url = ", a, fixed = TRUE)]
  if (!length(u)) return(NA_character_)
  trimws(sub("url = ", "", u[1], fixed = TRUE))
}

