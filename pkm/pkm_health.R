# Each one: snapshot first, byte-exact split, verify losslessness, and
# RESTORE FROM THE SNAPSHOT if verification fails. Never run automatically.

.snapshot <- function(paths) {
  arc <- file.path(PKM$drive, paste0("Projects_Index_archive_", format(Sys.Date())))
  dir.create(arc, showWarnings = FALSE)
  ok <- file.copy(paths, file.path(arc, basename(paths)), overwrite = TRUE)
  same <- file.info(paths)$size == file.info(file.path(arc, basename(paths)))$size
  if (!all(ok) || !all(same)) stop("snapshot failed -- aborting before any write")
  file.path(arc, basename(paths))
}

.spanner <- function(r) {
  nl <- which(r == as.raw(10)); N <- length(nl)
  list(N = N, get = function(a, b) {
    s <- if (a == 1) 1L else nl[a - 1] + 1L
    e <- if (b >= N) length(r) else nl[b]
    if (a > b) raw(0) else r[s:e]
  })
}

.verify <- function(orig_file, new_files, skip_head = 3) {
  o <- readLines(orig_file, warn = FALSE)
  n <- unlist(lapply(new_files, function(z) readLines(z, warn = FALSE)))
  body <- o[seq(skip_head + 1, length(o))]
  body <- body[nzchar(trimws(body))]
  setdiff(body, n)
}

split_tail <- function(file, dry_run = TRUE) {
  f <- file.path(PKM$index, file)
  if (!file.exists(f)) stop("no such file: ", file)
  a  <- readLines(f, warn = FALSE)
  li <- which(trimws(a) %in% c("# Log", "## Log", "### Log"))
  if (!length(li)) stop(file, " has no Log heading -- use a different remedy")
  li <- li[1]
  logfn <- sub("[.]md$", "_log.md", file)
  lf    <- file.path(PKM$logs, logfn)
  hf <- which(startsWith(a, "_")); hf <- hf[hf < 15]
  if (!length(hf)) stop("no header field block found in ", file)
  hf <- max(hf)
  has_ptr <- any(startsWith(a, "_Log: "))
  cut <- li - 1
  while (cut > 1 && !nzchar(trimws(a[cut]))) cut <- cut - 1
  if (trimws(a[cut]) == "---") cut <- cut - 1
  n_entries <- sum(startsWith(a[li:length(a)], "### 20"))
  if (dry_run) {
    message(file, ": Log heading at line ", li, ", ", n_entries,
            " dated entries, tail is ",
            round(nchar(paste(a[li:length(a)], collapse = "")) / 1024, 1), " KB")
    message("  -> would ", if (has_ptr) "APPEND to " else "CREATE ", logfn)
    return(invisible(NULL))
  }
  snap <- .snapshot(f)
  r <- readBin(f, "raw", file.info(f)$size); sp <- .spanner(r)
  ptr  <- if (has_ptr) raw(0) else charToRaw(paste0("_Log: logs/", logfn, "\r\n"))
  stub <- charToRaw(paste0("\r\n---\r\n## Log\r\n\r\nThe dated log for this project lives in `logs/",
            logfn, "`. Verbatim and unedited.\r\nNew entries go there, not here. (Split ",
            format(Sys.Date()), " by pkm_health.R)\r\n"))
  head <- c(sp$get(1, hf), ptr, sp$get(hf + 1, cut), stub)
  newtail <- sp$get(li, sp$N)
  if (has_ptr && file.exists(lf)) {
    tail <- c(readBin(lf, "raw", file.info(lf)$size), charToRaw("\r\n"), newtail)
  } else {
    tail <- c(charToRaw(paste0("# ", sub("^proj_", "", sub("[.]md$", "", file)),
      " -- project log\r\n_Split from ", file, " on ", format(Sys.Date()),
      ". Verbatim; nothing edited._\r\n_Live project file: `../", file, "`_\r\n\r\n---\r\n\r\n")),
      newtail)
  }
  writeBin(head, f); writeBin(tail, lf)
  miss <- .verify(snap, c(f, lf))
  if (length(miss)) {
    file.copy(snap, f, overwrite = TRUE)
    stop("VERIFICATION FAILED (", length(miss), " lines unaccounted). Restored from snapshot.")
  }
  message(file, ": ", .kb(snap), " -> ", .kb(f), " KB | ", logfn, " = ", .kb(lf),
          " KB | lossless (", n_entries, " entries moved)")
  invisible(TRUE)
}

archive_focus <- function(new_focus = NULL, dry_run = TRUE) {
  f <- file.path(PKM$index, "project_index.md")
  h <- file.path(PKM$logs, "focus_history.md")
  a <- readLines(f, warn = FALSE)
  i <- which(startsWith(a, "**Active Focus"))
  if (!length(i)) stop("no Active Focus block found")
  i <- i[1]
  if (dry_run) {
    message("Active Focus at line ", i, " is ", round(nchar(a[i]) / 1024, 1),
            " KB -> would move to logs/focus_history.md")
    return(invisible(NULL))
  }
  snap <- .snapshot(c(f, h))
  r <- readBin(f, "raw", file.info(f)$size); sp <- .spanner(r)
  block <- sp$get(i, i)
  repl <- if (is.null(new_focus)) charToRaw(paste0(
      "**Active Focus (", format(Sys.Date()), "): NOT YET SET** -- previous focus archived to ",
      "`logs/focus_history.md`. Confirm or redirect at session start.\r\n"))
    else charToRaw(paste0(new_focus, "\r\n"))
  writeBin(c(sp$get(1, i - 1), repl, sp$get(i + 1, sp$N)), f)
  hr <- readBin(h, "raw", file.info(h)$size)
  mark <- charToRaw("## Superseded Active Focus blocks\r\n\r\n")
  pos <- grepRaw(mark, hr, fixed = TRUE)
  if (!length(pos)) { file.copy(snap, c(f, h), overwrite = TRUE); stop("marker not found; restored") }
  at <- pos[1] + length(mark)
  note <- charToRaw(paste0("<!-- superseded ", format(Sys.Date()), " -->\r\n"))
  writeBin(c(hr[seq_len(at - 1)], note, block, charToRaw("\r\n"), hr[at:length(hr)]), h)
  message("focus block archived: project_index.md now ", .kb(f), " KB")
  invisible(TRUE)
}

split_session_log <- function(keep = 15, dry_run = TRUE) {
  f <- file.path(PKM$index, "session_log.md")
  g <- file.path(PKM$logs, "session_log_archive.md")
  a <- readLines(f, warn = FALSE)
  hd <- which(startsWith(a, "## "))
  if (length(hd) <= keep) { message("only ", length(hd), " entries -- nothing to archive"); return(invisible(NULL)) }
  cutline <- hd[keep + 1]
  if (dry_run) {
    message(length(hd), " entries; keeping ", keep, ", archiving ", length(hd) - keep,
            " from line ", cutline, " (", round(nchar(paste(a[cutline:length(a)], collapse="")) / 1024, 1), " KB)")
    return(invisible(NULL))
  }
  snap <- .snapshot(f)
  r <- readBin(f, "raw", file.info(f)$size); sp <- .spanner(r)
  note <- charToRaw(paste0("\r\n---\r\n\r\nOlder entries (", length(hd) - keep,
    ") were moved to `logs/session_log_archive.md` on ", format(Sys.Date()),
    " by pkm_health.R.\r\nThey are verbatim. Search there before concluding an entry is missing.\r\n"))
  hdr <- charToRaw(paste0("# Session Log -- archive\r\n_Split from session_log.md on ",
    format(Sys.Date()), ". Verbatim; nothing edited._\r\n\r\n---\r\n\r\n"))
  writeBin(c(sp$get(1, cutline - 1), note), f)
  writeBin(c(hdr, sp$get(cutline, sp$N)), g)
  miss <- .verify(snap, c(f, g), skip_head = 0)
  if (length(miss)) { file.copy(snap, f, overwrite = TRUE)
    stop("VERIFICATION FAILED (", length(miss), " lines). Restored from snapshot.") }
  message("session_log.md: ", .kb(snap), " -> ", .kb(f), " KB | archive = ", .kb(g), " KB | lossless")
  invisible(TRUE)
}


