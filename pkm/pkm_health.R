## ---- small helpers --------------------------------------------------

.kb <- function(paths) round(file.info(paths)$size / 1024, 1)

.read <- function(f) readLines(f, warn = FALSE)

.front_matter <- function(f) {
  a <- .read(f)
  d <- which(trimws(a) == "---")
  if (length(d) < 2 || d[1] != 1) return(NULL)
  y <- tryCatch(yaml::yaml.load(paste(a[(d[1] + 1):(d[2] - 1)], collapse = "\n")),
                error = function(e) NULL)
  y
}

.flat <- function(v) if (is.null(v)) NA_character_ else paste(unlist(v), collapse = "; ")

.probe <- function(url, timeout = 20) {
  h <- curl::new_handle(nobody = TRUE, followlocation = TRUE, timeout = timeout)
  r <- tryCatch(curl::curl_fetch_memory(url, handle = h), error = function(e) NULL)
  if (is.null(r)) NA_integer_ else r$status_code
}

## ---- JOB 1: generate the works register -----------------------------

pkm_works <- function() {
  out <- list()
  for (i in seq_len(nrow(PKM$venues))) {
    v <- PKM$venues[i, ]
    dir <- if (v$subdir == ".") file.path(PKM$drive, v$folder)
           else file.path(PKM$drive, v$folder, v$subdir)
    if (!dir.exists(dir)) next
    qs <- list.files(dir, pattern = "[.]qmd$", full.names = TRUE)
    qs <- qs[basename(qs) != "index.qmd"]
    qs <- qs[!startsWith(basename(qs), "_")]
    for (q in qs) {
      fm   <- .front_matter(q)
      slug <- sub("[.]qmd$", "", basename(q))
      rel  <- if (v$subdir == ".") paste0(slug, ".html")
              else paste0(v$subdir, "/", slug, ".html")
      out[[length(out) + 1]] <- data.frame(
        venue    = v$venue,
        slug     = slug,
        title    = .flat(fm$title),
        subtitle = .flat(fm$subtitle),
        date     = .flat(fm$date),
        categories = .flat(fm$categories),
        pdf      = .flat(fm$pdf),
        source   = q,
        rel      = rel,
        url      = paste0(v$url, "/", rel),
        modified = format(file.info(q)$mtime, "%Y-%m-%d"),
        stringsAsFactors = FALSE)
    }
  }
  w <- do.call(rbind, out)
  w[order(w$venue, w$slug), ]
}

pkm_register <- function(write = TRUE) {
  w <- pkm_works()
  if (!write) return(w)
  n <- table(w$venue)
  L <- c("# Works Register",
         paste0("_Generated by pkm_health.R on ", format(Sys.Date()), ". DO NOT EDIT BY HAND._"),
         "",
         "One row per published work across the four venues. A work is tracked here,",
         "not as a proj_*.md file. A work earns a proj_*.md only when it acquires",
         "DEVELOPMENT -- code, a package, a method, a multi-session build.",
         "",
         paste0("**", nrow(w), " works** -- ",
                paste(paste0(names(n), " ", as.integer(n)), collapse = ", ")),
         "")
  for (v in PKM$venues$venue) {
    s <- w[w$venue == v, ]
    if (!nrow(s)) next
    L <- c(L, paste0("## ", v, " (", nrow(s), ")"), "",
           "| Work | Date | Categories | Live URL |",
           "|---|---|---|---|")
    for (j in seq_len(nrow(s)))
      L <- c(L, paste0("| ", s$title[j], " | ", s$date[j], " | ",
                       s$categories[j], " | ", s$rel[j], " |"))
    L <- c(L, "")
  }
  f <- file.path(PKM$index, "works_register.md")
  writeLines(L, f)
  message("wrote ", f, " -- ", nrow(w), " works")
  invisible(w)
}

## ---- JOB 2: reconcile source -> _site -> live -----------------------

pkm_reconcile <- function(check_live = TRUE) {
  w <- pkm_works()
  w$rendered <- NA; w$live <- NA_integer_
  for (i in seq_len(nrow(w))) {
    v <- PKM$venues[PKM$venues$venue == w$venue[i], ]
    w$rendered[i] <- file.exists(file.path(PKM$drive, v$folder, "_site", w$rel[i]))
    if (check_live) w$live[i] <- .probe(w$url[i])
  }
  w$ok <- w$rendered & (!check_live | (!is.na(w$live) & w$live == 200))
  w
}

pkm_orphans <- function() {
  out <- list()
  for (i in seq_len(nrow(PKM$venues))) {
    v  <- PKM$venues[i, ]
    sub_ <- if (v$subdir == ".") "" else v$subdir
    sd <- file.path(PKM$drive, v$folder, "_site", sub_)
    bd <- file.path(PKM$drive, v$folder, sub_)
    if (!dir.exists(sd)) next
    html <- list.files(sd, pattern = "[.]html$")
    html <- html[html != "index.html"]
    # Quarto renders .md as well as .qmd -- accept either as a source
    q <- file.path(bd, sub("[.]html$", ".qmd", html))
    m <- file.path(bd, sub("[.]html$", ".md",  html))
    miss <- html[!file.exists(q) & !file.exists(m)]
    if (length(miss))
      out[[length(out) + 1]] <- data.frame(venue = v$venue,
        rendered_without_source = miss, stringsAsFactors = FALSE)
  }
  if (!length(out)) return(data.frame())
  do.call(rbind, out)
}

## ---- JOB 3: verify _Log: pointers -----------------------------------

pkm_pointers <- function() {
  pf <- list.files(PKM$index, pattern = "[.]md$", full.names = TRUE)
  ptr <- list(); ref <- character(0)
  for (z in pf) {
    a <- .read(z); h <- a[seq_len(min(15, length(a)))]
    p <- h[startsWith(h, "_Log: ")]
    if (!length(p)) next
    tgt <- sub("_$", "", substring(p[1], 7))
    ref <- c(ref, basename(tgt))
    ptr[[length(ptr) + 1]] <- data.frame(file = basename(z), pointer = tgt,
      resolves = file.exists(file.path(PKM$index, tgt)), stringsAsFactors = FALSE)
  }
  ptr <- if (length(ptr)) do.call(rbind, ptr) else data.frame()
  have <- list.files(PKM$logs, pattern = "[.]md$")
  list(pointers = ptr,
       broken   = if (nrow(ptr)) ptr$file[!ptr$resolves] else character(0),
       orphans  = setdiff(setdiff(have, ref), c("focus_history.md", "session_log_archive.md")))
}

