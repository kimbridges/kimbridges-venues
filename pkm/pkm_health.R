# Revised 2026-08-03 after measuring. Kim: "We should not be storing derived
# output. That simply wastes space and is not the intent of this backup."
#
# The first cut used VENUE_GITIGNORE -- a BLACKLIST -- and it could not keep up:
# it missed `_output/` (the output-dir every book project uses), so 7 rendered
# Gallery Catalog pages would have been committed. It also admitted 2018 files of
# Jones research data and 278 rendered pages from the documents venue.
# A blacklist has to anticipate every kind of junk. A WHITELIST only has to know
# what source looks like, and that list barely changes.

VENUE_MIRROR <- "C:/repos/kimbridges-venues"

# Hand-authored code and markup. NOT .txt/.csv/.json/.docx -- those are DATA.
SOURCE_EXT <- c("qmd", "rmd", "r", "yml", "yaml", "css", "scss",
                "bib", "py", "js", "md",
                # DATA extensions added 2026-08-18 on Kim's decision (Finding 034).
                # The mirror had never carried a single csv: 82 of 85 files in
                # Projects/Smart_Car were outside the backup while it reported success.
                # Kim: "these files are where data live and that's often our focus".
                # Cost measured before the change: 182 files / 1.8 MB across all projects.
                "csv", "xlsx")

# Hand-authored .html helpers. `html` is NOT in SOURCE_EXT: a first pass admitted
# 12.5 MB of rendered output living outside any _site/_output folder -- R Notebook
# renders, htmlwidget maps, loose Quarto pages. Allowlist by name instead.
SOURCE_FILES <- c("viewer.html")

# Build products and tool state. Anything under these never enters the mirror.
DERIVED_DIRS <- c("_site", "_book", "_output", "_freeze", ".quarto",
                  "site_libs", ".Rproj.user", ".git", "libs")

# Venues holding COPIED-IN rendered documents rather than their own source.
# kimbridges-documents: every top-level folder except docs/ is a rendered document
# whose real source lives in Projects/<name>. Stated as a rule, not a list, so it
# stays true as documents are added.
VENUE_SOURCE_ROOTS <- list("kimbridges-documents" = c(".", "docs"))

.is_source <- function(rel) {
  seg <- strsplit(rel, "/", fixed = TRUE)
  bad <- vapply(seg, function(s) any(s %in% DERIVED_DIRS) ||
                                 any(startsWith(s, "_backup")), logical(1))
  bad <- bad | grepl("\\.~lock\\.", rel, fixed = FALSE)
  # Office lock/owner files. LibreOffice writes .~lock.NAME# ; Excel writes ~$NAME.
  # Added 2026-08-18: allowing xlsx into SOURCE_EXT immediately pulled in a ~$ owner file,
  # which is LOCKED, so it reports a size at source and copies as 0 bytes -- tripping the
  # size-mismatch guard and aborting the whole backup before the commit. Not data; exclude.
  bad <- bad | startsWith(basename(rel), "~$")   # LibreOffice lock files
  ext <- tolower(sub(".*\\.", "", basename(rel)))
  !bad & (ext %in% SOURCE_EXT | basename(rel) %in% SOURCE_FILES)
}

# List the hand-authored source of one folder. Names first, filter BEFORE any
# stat call -- stat-ing every file across Drive Stream venues stalled the bridge.
.src_files <- function(dir, roots = NULL) {
  f <- list.files(dir, recursive = TRUE, all.files = TRUE, no.. = TRUE)
  if (!length(f)) return(character(0))
  if (!is.null(roots)) {
    top <- ifelse(grepl("/", f), sub("/.*", "", f), ".")
    f <- f[top %in% roots]
  }
  sort(f[.is_source(f)])
}

# Refresh one folder's mirror. Returns a summary; does NOT commit.
pkm_mirror <- function(name, from, into = VENUE_MIRROR, roots = NULL) {
  src <- from
  dst <- file.path(into, name)
  if (!dir.exists(src)) stop("no such folder: ", src)
  keep <- .src_files(src, roots)
  dir.create(dst, recursive = TRUE, showWarnings = FALSE)
  for (d in unique(dirname(keep))) if (d != ".")
    dir.create(file.path(dst, d), recursive = TRUE, showWarnings = FALSE)
  copied <- if (length(keep))
    file.copy(file.path(src, keep), file.path(dst, keep),
              overwrite = TRUE, copy.date = TRUE) else logical(0)
  cur  <- list.files(dst, recursive = TRUE, all.files = TRUE, no.. = TRUE)
  cur  <- cur[!startsWith(cur, ".git/")]
  # tolower BOTH sides -- Finding 021: a case-only rename is one file on Windows
  orph <- cur[!(tolower(cur) %in% tolower(keep))]
  if (length(orph)) file.remove(file.path(dst, orph))
  a <- file.info(file.path(src, keep))$size
  b <- file.info(file.path(dst, keep))$size
  list(name = name, tracked = length(keep), copied = sum(copied),
       orphans_removed = length(orph), size_mismatch = sum(a != b, na.rm = TRUE),
       kb = round(sum(b, na.rm = TRUE) / 1024, 1))
}

pkm_mirror_venue <- function(venue, into = VENUE_MIRROR, drive = PKM$drive)
