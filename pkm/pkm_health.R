.drop_tail <- function(z) {
  z <- trimws(z)
  while (nchar(z) > 0 &&
         substring(z, nchar(z)) %in% c(",", ";", ".", "(", ")", "/", "-", ":", "*"))
    z <- trimws(substring(z, 1, nchar(z) - 1))
  z
}

.resolve_path <- function(s) {
  s <- .drop_tail(s)
  if (!grepl("/", s, fixed = TRUE)) return(NA_character_)   # prose, not a path
  for (k in seq_len(15)) {
    if (file.exists(s)) return(s)          # dirs AND files both count
    parts <- strsplit(s, " ", fixed = TRUE)[[1]]
    if (length(parts) <= 1) break
    s <- .drop_tail(paste(parts[-length(parts)], collapse = " "))
  }
  NA_character_
}

.extract_paths <- function(line) {
  bs <- rawToChar(as.raw(92))
  ln <- gsub(bs, "/", line, fixed = TRUE)
  out <- character(0)
  for (p in strsplit(ln, "`", fixed = TRUE)[[1]]) {
    k <- regexpr("G:", p, fixed = TRUE)
    if (k > 0) out <- c(out, substring(p, k))
  }
  out
}

# Bounded scan: a full recursive walk of a Projects/ folder over Drive
# Stream hangs the bridge (learned 2026-07-30 -- two 60s timeouts). Depth 2,
# capped, and the big generated folders skipped. This is a DRIFT FLAG, not a
# census; it only needs the newest interesting mtime.
.SKIP_DIRS <- c("_site", "_book", "_output", ".quarto", ".git", "renv",
                "site_libs", "_freeze", ".Rproj.user")

.newest_mtime <- function(d, max_dirs = 40, max_files = 3000) {
  if (!dir.exists(d)) return(file.info(d)$mtime)   # a single named file
  e <- list.files(d, full.names = TRUE)
  isdir <- dir.exists(e)
  subs <- e[isdir]
  subs <- subs[!basename(subs) %in% .SKIP_DIRS]
  all <- e[!isdir]
  for (s in head(subs, max_dirs)) {
    g <- list.files(s, full.names = TRUE)
    g <- g[!basename(g) %in% .SKIP_DIRS]
    all <- c(all, g)
    if (length(all) > max_files) break
  }
  all <- head(all, max_files)
  if (!length(all)) return(as.POSIXct(NA))
  suppressWarnings(max(file.info(all)$mtime, na.rm = TRUE))
}

.status_of <- function(z) {
  h <- readLines(z, n = 10, warn = FALSE)
  s <- h[startsWith(h, "_Status:")]
  if (!length(s)) return(NA_character_)
  v <- trimws(sub("_Status:", "", s[1], fixed = TRUE))
  strsplit(sub("_$", "", v), " ")[[1]][1]
}

# Drift is only meaningful for ACTIVE projects: a Complete project whose
# folder is newer than its proj file is normal, and a Standing venue
# receives work continuously by definition. Scoping to Active cut this from
# over 60s (two bridge timeouts on 2026-07-30) to a couple of seconds.
pkm_drift <- function(min_days = 7, statuses = "Active") {
  skip_roots <- file.path(PKM$drive,
    c(PKM$venues$folder, "kimbridges-info", "Projects_Index"))
  too_broad <- c("G:/My Drive", "G:/My Drive/Projects", "G:/My Drive/Projects_Index")
  pf <- list.files(PKM$index, pattern = "[.]md$", full.names = TRUE)
  pf <- pf[startsWith(basename(pf), "proj_")]
  pf <- pf[vapply(pf, function(z) isTRUE(.status_of(z) %in% statuses), logical(1))]
  out <- list()
  for (z in pf) {
    a <- .read(z)
    s <- which(startsWith(a, "## Locations"))
    if (!length(s)) next
    e <- which(startsWith(a, "## ")); e <- e[e > s[1]]
    blk <- a[s[1]:(if (length(e)) e[1] - 1 else length(a))]
    raws <- unique(unlist(lapply(blk, .extract_paths)))
    seen <- character(0)
    for (rw in raws) {
      if (!grepl("/", rw, fixed = TRUE)) next   # prose, not a path
      d <- .resolve_path(rw)
      if (is.na(d)) {
        out[[length(out) + 1]] <- data.frame(file = basename(z),
          location = substr(rw, 1, 55), issue = "location not found",
          days = NA_real_, stringsAsFactors = FALSE); next
      }
      if (d %in% too_broad || d %in% seen) next
      if (any(startsWith(d, skip_roots))) next
      seen <- c(seen, d)
      newest <- .newest_mtime(d)
      if (!is.finite(newest)) next
      gap <- as.numeric(difftime(newest, file.info(z)$mtime, units = "days"))
      if (gap > min_days)
        out[[length(out) + 1]] <- data.frame(file = basename(z), location = d,
          issue = "code newer than the proj file", days = round(gap, 1),
          stringsAsFactors = FALSE)
    }
  }
  if (!length(out)) return(data.frame())
  o <- do.call(rbind, out)
  o[order(-replace(o$days, is.na(o$days), -1)), ]
}

## ---- JOB 5: size budget (the flow control, added 2026-07-30) --------

pkm_budget <- function() {
  fs <- list.files(PKM$index, pattern = "[.]md$", full.names = TRUE)
  b <- PKM$budget
  cls <- function(n) if (n %in% names(b$hot)) "HOT"
                     else if (n == "session_log.md") "REFERENCE"
                     else if (startsWith(n, "proj_")) "PROJECT" else "REFERENCE"
  lim <- function(n) if (n %in% names(b$hot)) unname(b$hot[n])
                     else if (n == "session_log.md") b$session_log
                     else if (startsWith(n, "proj_")) b$proj else b$reference
  d <- data.frame(file = basename(fs), kb = .kb(fs), stringsAsFactors = FALSE)
  d$class <- vapply(d$file, cls, character(1))
  d$budget_kb <- vapply(d$file, lim, numeric(1))
  d$over <- round(d$kb - d$budget_kb, 1)
  d$splittable <- vapply(fs, function(z) {
    x <- .read(z); any(trimws(x) %in% c("# Log", "## Log", "### Log")) }, logical(1))
  d <- d[d$over > 0, ]
  d[order(-d$over), c("file", "class", "kb", "budget_kb", "over", "splittable")]
}

# Bucket 4 retention (Tier 3): build scratch is regenerable and must not linger.
# Bucket 4 retention. The rule is "delete once the deploy is verified live",
# which no clock can detect -- so report EVERY scratch folder, and mark the ones
# past the threshold. A check that answers "none" while 226 MB sits stranded is
# worse than no check: it certifies a problem as absent. (2026-07-31)
pkm_scratch <- function(days = PKM$scratch_days) {
  root <- "C:/temp"
  if (!dir.exists(root)) return(data.frame())
  d <- list.dirs(root, recursive = FALSE)
  if (!length(d)) return(data.frame())
  age <- as.numeric(difftime(Sys.time(), file.info(d)$mtime, units = "days"))
  mb <- vapply(d, function(z) {
    fs <- list.files(z, recursive = TRUE, full.names = TRUE)
    if (!length(fs)) 0 else round(sum(file.info(fs)$size, na.rm = TRUE) / 1048576) },
    numeric(1))
  out <- data.frame(folder = basename(d), age_days = round(age, 1), MB = mb,
                    past_threshold = age > days, stringsAsFactors = FALSE)
  out[order(-out$MB), ]
}

