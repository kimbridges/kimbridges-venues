pkm_consolidation <- function(check_legacy = TRUE) {
  repos <- .gh_repos()
  vf <- c(PKM$venues$folder, "kimbridges-info")
  ven <- data.frame(site = vf,
    has_git = dir.exists(file.path(PKM$drive, vf, ".git")),
    remote  = vapply(file.path(PKM$drive, vf), .git_remote, character(1)),
    gitignore = file.exists(file.path(PKM$drive, vf, ".gitignore")),
    stringsAsFactors = FALSE)
  pd <- list.dirs(file.path(PKM$drive, "Projects"), recursive = FALSE)
  prj <- data.frame(project = basename(pd),
    local_clone = dir.exists(file.path(pd, ".git")),
    public_repo = basename(pd) %in% repos,
    stringsAsFactors = FALSE)
  prj$issue <- ifelse(prj$local_clone & !prj$public_repo, "clone but no public repo",
               ifelse(!prj$local_clone & prj$public_repo, "public repo but no local clone", ""))
  leg <- data.frame()
  if (check_legacy) {
    a <- .read(file.path(PKM$index, "inventory_all_projects.md"))
    grab <- function(pat) {
      out <- character(0)
      for (ln in a) {
        k <- regexpr(pat, ln, fixed = TRUE)
        if (k > 0) {
          s <- strsplit(substring(ln, k), "[ )>,]")[[1]][1]
          if (nchar(s) > nchar(pat) + 2) out <- c(out, sub("[.,]$", "", s))
        }
      }
      unique(out)
    }
    for (pl in c("https://kim.quarto.pub", "hflip.co", "exposure.co",
                 "soundcloud.com", "issuu.com/kimbridges")) {
      u <- grab(pl)
      if (length(u)) leg <- rbind(leg, data.frame(platform = pl, url = u,
                                                  stringsAsFactors = FALSE))
    }
  }
  list(venues = ven, projects = prj[prj$issue != "", ], legacy = leg,
       repos = repos,
       venues_without_repo = sum(!ven$has_git),
       legacy_pages = nrow(leg))
}


## ---- JOB 7: legacy gap -- the PRE-DELETION GATE ---------------------
# Kim will retire Quarto Pub / hflip / Exposure by DELETING THE ACCOUNTS,
# not item by item (per-item deletion is impractical; Quarto Pub blocks it).
# That is a ONE-WAY DOOR: every page goes at once and its links break. So the
# gate before deleting an account is: does every page on it have an
# equivalent on a kimbridges venue?
#
# MATCHING LESSON (2026-07-30): match on the PDF FILENAME first. Legacy slugs
# name the PDF (hflip.co/merritt_island.html) while venue slugs name the story
# (wading-birds-of-black-point-wildlife-drive). Slug-to-slug matching reported
# 22 orphans; PDF-first matching reduced it to 2. Do not trust a token score
# alone -- it is a triage aid, not a verdict.
.LSTOP <- c("the","of","in","and","a","at","on","to","for","my","an","is","part")
.ltok <- function(s) { s <- tolower(s)
  for (ch in c("-","_",".","/","'",":",",")) s <- gsub(ch, " ", s, fixed = TRUE)
  t <- strsplit(trimws(s), " +")[[1]]; unique(t[nchar(t) > 2 & !t %in% .LSTOP]) }
.lnorm <- function(s) { s <- tolower(s)
  for (ch in c("-","_",".","/"," ","'")) s <- gsub(ch, "", s, fixed = TRUE); s }
.lscore <- function(A, B) { if (!length(A) || !length(B)) return(0)
  round(sum(vapply(A, function(x) any(x == B |
    (nchar(x) >= 4 & substr(B, 1, 4) == substr(x, 1, 4))), logical(1))) /
    min(length(A), length(B)), 2) }

pkm_legacy_gap <- function() {
  w <- pkm_works()
  nested <- list.files(file.path(PKM$drive, "kimbridges-collections"),
                       pattern = "[.]qmd$", recursive = TRUE)
  nested <- nested[grepl("/", nested, fixed = TRUE)]
  key <- rbind(data.frame(slug = w$slug, title = w$title, pdf = w$pdf,
                          stringsAsFactors = FALSE),
               data.frame(slug = sub("[.]qmd$", "", basename(nested)),
                          title = sub("[.]qmd$", "", basename(nested)),
                          pdf = NA_character_, stringsAsFactors = FALSE))
  key$pdfbase <- ifelse(is.na(key$pdf), NA_character_,
                        sub("[.]pdf$", "", basename(key$pdf)))
  leg <- pkm_consolidation()$legacy
  leg$slug <- vapply(leg$url, function(u) {
    p <- strsplit(sub("/$", "", u), "/", fixed = TRUE)[[1]]
    sub("[.]html$", "", p[length(p)]) }, character(1))
  leg <- leg[nchar(leg$slug) > 2 & !leg$slug %in% c("hflip", "hflip:"), ]
  nk <- .lnorm(key$slug); nt <- .lnorm(key$title)
  np <- .lnorm(ifelse(is.na(key$pdfbase), "~~", key$pdfbase))
  kt <- lapply(seq_len(nrow(key)), function(i) unique(c(.ltok(key$slug[i]),
         .ltok(key$title[i]), if (!is.na(key$pdfbase[i])) .ltok(key$pdfbase[i]))))
  r <- t(vapply(leg$slug, function(s) {
    ns <- .lnorm(s)
    j <- which(np == ns); if (length(j)) return(c(key$slug[j[1]], "1", "pdf-exact"))
    j <- which(nk == ns | nt == ns); if (length(j)) return(c(key$slug[j[1]], "1", "slug-exact"))
    v <- vapply(kt, function(B) .lscore(.ltok(s), B), numeric(1)); j <- which.max(v)
    c(key$slug[j], as.character(v[j]), "token") }, character(3)))
  leg$match <- r[, 1]; leg$score <- as.numeric(r[, 2]); leg$how <- r[, 3]
  # WEAK-EVIDENCE GUARD, added 2026-08-01 after a FALSE ALL-CLEAR.
  # `ai-podcasts` matched the Gallery Catalog `Podcast` page at score 1.0 and was
  # reported as "matched", so the gate said 0 hard gaps for Quarto Pub. After the
  # tokeniser drops words under 3 characters, "ai-podcasts" is a SINGLE token; one
  # token matching one token on a 4-character prefix always scores 1.0. A perfect
  # score on one token is not evidence. Such matches are now REVIEW, never matched.
  ntok <- vapply(leg$slug,  function(s) length(.ltok(s)), integer(1))
  mtok <- vapply(leg$match, function(s) length(.ltok(s)), integer(1))
  leg$evidence <- ifelse(leg$how != "token", "exact",
                  ifelse(pmin(ntok, mtok) < 2, "WEAK - one token only", "tokens"))
  leg$verdict <- ifelse(leg$score >= 0.66, "matched",
                 ifelse(leg$score >= 0.34, "possible", "NONE"))
  leg$verdict[leg$evidence == "WEAK - one token only" & leg$verdict == "matched"] <- "REVIEW"
  leg[order(leg$score, leg$platform), c("platform","slug","match","score","how","evidence","verdict")]
}

