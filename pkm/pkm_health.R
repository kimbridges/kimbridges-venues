## ---- JOB 7b: legacy links seen LIVE in the venues -------------------
# WHY THIS EXISTS. pkm_legacy_gap() reads inventory_all_projects.md, so it
# can only protect platforms the INVENTORY records. Eleven SoundCloud embeds
# sat inside published venue pages for months and the gate never saw one of
# them, because no inventory row mentioned SoundCloud (2026-08-02). This
# function goes to ground truth instead: it reads the venue files themselves.
# Run BOTH. Disagreement between them is the finding.
pkm_legacy_live <- function(platforms = c("quarto[. ]pub\\b", "hflip", "exposure\\.co",
                                          "soundcloud", "issuu\\.com"),
                            sources = TRUE) {
  vf  <- c(PKM$venues$folder, "kimbridges-info")
  out <- data.frame()
  for (v in vf) {
    root <- file.path(PKM$drive, v)
    if (!dir.exists(root)) next
    f <- list.files(root, pattern = "[.](qmd|md|html)$", recursive = TRUE,
                    full.names = TRUE)
    # SOURCE only by default: rendered output just mirrors it, at 10x the files
    if (sources) f <- f[!grepl("/_site/|/_output/|/_book/|/site_libs/", f)]
    f <- f[!grepl("/_backup", f)]
    for (pth in f) {
      a <- readLines(pth, warn = FALSE)
      for (pl in platforms) {
        k <- grep(pl, a, ignore.case = TRUE)
        for (j in k) {
          u <- regmatches(a[j], gregexpr("https?://[^ )\"'<]+", a[j]))[[1]]
          u <- u[grepl(pl, u, ignore.case = TRUE)]
          out <- rbind(out, data.frame(venue = v, platform = pl,
                 file = sub(paste0(PKM$drive, "/"), "", pth, fixed = TRUE),
                 line = j, url = if (length(u)) paste(u, collapse = " ") else "",
                 stringsAsFactors = FALSE))
        }
      }
    }
  }
  if (!nrow(out)) return(out)
  # a link with no URL on the line is prose mentioning the platform, not a pointer
  out$kind <- ifelse(out$url == "", "mention only", "LINK")
  out[order(out$platform, out$venue, out$file, out$line), ]
}


